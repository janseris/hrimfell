#!/usr/bin/env python3
# (v0.4.72) Forelhost's books and notes from the export's books.csv (their texts, as Skyrim has them) and refs.csv.gz
# (where each lies): the texts turned into the game's pages, the places into a table game_fhquest.cpp lays out.
#   python3 docs/maps/gen_fh_books.py /home/claude/fh_in3/skyrim_forelhost src/fh_books.inc
# Skyrim's markup: [pagebreak] a new page; <img ... Illuminated_Letters/X_letter.png> the first letter drawn large (here
# the letter); the other tags (font, p, img) dropped. Pages are filled as Game::DrawWrapped lays them out at 320 wide
# (44 characters a line, 14 lines; '\n' a new line, '|' a new page) - a page too long for the screen goes on to the next.
import csv, gzip, os, re, sys, unicodedata
EXP, OUT = sys.argv[1], sys.argv[2]
# the game's items, in this order (the journal's place is the quest's - game_fhquest.cpp)
ORDER = [('dunForelhostJournal', 'IT_FH_JOURNAL'), ('dunForelhostAlchemistNote01', 'IT_FH_NOTE_FRODA'),
         ('dunForelhostAlchemistNote02', 'IT_FH_NOTE_RAHGOT'), ('dunForelhostGardenNote01', 'IT_FH_NOTE_ORDERS'),
         ('dunForelhostPoisonNote01', 'IT_FH_NOTE_POISON'), ('dunForelhostDeathNote01', 'IT_FH_NOTE_DEATH'),
         ('SkillRestoration3', 'IT_BK_EXODUS'), ('SpellTomeFlames', 'IT_TOME_FLAMES')]
CELLS = {'Forelhost01': 'CELL_FHSTRONG', 'Forelhost02': 'CELL_FHCRYPT', 'Forelhost03': 'CELL_FHREFECT'}
MAXC, LINES = 44, 14

books = {r['editor_id']: r for r in csv.DictReader(open(os.path.join(EXP, 'books.csv'), encoding='utf-8'))}
refs = [r for r in csv.DictReader(gzip.open(os.path.join(EXP, 'refs.csv.gz'), 'rt', encoding='utf-8'))
        if r['base_type'] == 'BOOK' and r['cell'] in CELLS]

def clean(t):
    t = t.replace('\\n', '\n').replace('\r', '')
    t = re.sub(r"<img src='img://Textures/Interface/Books/Illuminated_Letters/(\w)_letter\.png'[^>]*>", r'\1', t)
    t = re.sub(r'<[^>]*>', '', t)
    t = unicodedata.normalize('NFKD', t).encode('ascii', 'ignore').decode()
    t = t.replace('|', '/')
    pages = []
    for p in t.split('[pagebreak]'):
        lines = [l.rstrip() for l in p.split('\n')]
        p = re.sub(r'\n{3,}', '\n\n', '\n'.join(lines)).strip('\n ')
        if p: pages.append(p)
    return pages

def wrap_lines(p):
    # the starts of the lines DrawWrapped makes of a page (its rules exactly)
    starts, i = [], 0
    while i < len(p):
        while i < len(p) and p[i] == ' ': i += 1
        if i >= len(p): break
        starts.append(i)
        n, last = 0, -1
        while i + n < len(p) and p[i + n] != '\n' and n < MAXC:
            if p[i + n] == ' ': last = n
            n += 1
        take = n
        if i + n < len(p) and p[i + n] != '\n' and last > 0: take = last
        i += take
        if i < len(p) and p[i] == '\n': i += 1
    return starts

def paginate(pages):
    out = []
    for p in pages:
        while True:
            st = wrap_lines(p)
            if len(st) <= LINES: out.append(p); break
            cut = st[LINES]
            out.append(p[:cut].rstrip('\n '))
            p = p[cut:].lstrip('\n ')
            if not p: break
    return out

def cstr(s):
    s = s.replace('\\', '\\\\').replace('"', '\\"')
    parts = s.split('\n')
    return '\n        '.join('"%s%s"' % (q, '\\n' if k < len(parts) - 1 else '') for k, q in enumerate(parts))

out = ['// generated by docs/maps/gen_fh_books.py from the %s export: Forelhost\'s books and notes, Skyrim\'s texts' % os.path.basename(EXP)]
out.append('static const char* const KFhBooks[%d] =\n    {' % len(ORDER))
meta = []
for ed, it in ORDER:
    b = books[ed]
    pages = paginate(clean(b['text']))
    out.append('    // %s "%s" (%s): %d pages' % (ed, b['name'], it, len(pages)))
    out.append('    ' + cstr('|'.join(pages)) + ',')
    meta.append((it, b.get('value', ''), b.get('weight', '')))
    print('%-30s %-30s %2d pages  value %s weight %s' % (ed, b['name'], len(pages), b.get('value', '?'), b.get('weight', '?')))
out.append('    };')
# where each lies (Skyrim units; the journal left to the quest)
out.append('// item, cell, x, y, z (Skyrim units: y north, z up), turn (degrees)')
out.append('static const int KFhBookPlace[] =\n    {')
for r in refs:
    names = [it for ed, it in ORDER if ed == r['base_editor_id']]
    if not names or names[0] == 'IT_FH_JOURNAL': continue
    out.append('    %s, %s, %d, %d, %d, %d,' % (names[0], CELLS[r['cell']], round(float(r['x'])), round(float(r['y'])),
                                              round(float(r['z'])), round(float(r['rot_z']))))
out.append('    -1 };')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote', OUT)
