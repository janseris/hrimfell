#!/usr/bin/env python3
# (v0.4.55) Bleak Falls Barrow's working parts in Skyrim's own halls (data/bleakfalls.har: CELL_BFTEMPLE <- Skyrim's
# BleakFallsBarrow01, CELL_BFSANCTUM <- BleakFallsBarrow02): the same tables game_dungeon.cpp has for the game's built
# barrow (bfb.inc), from where Skyrim places each thing (the bleakfalls export, tools/skyrim_area.py bleakfalls):
# the puzzle pillars, the lever, the gates, the pull chains, the claw door, the word wall, the traps (blades, the
# pressure plate and its spike wall, the darts, the oil and its lanterns), the sarcophagus' lid; the bandits, Arvel, the
# spider, the skeevers, the draugr and their Overlord. In the interiors' frame (cm, y up from the floor level):
# x = Skyrim x * 1.43, y = Skyrim z * 1.43, z = Skyrim y * 1.43 (the kit's own: game_kit.cpp U()).
#   python3 docs/maps/gen_bfb_kit.py /home/claude/bfb_in2/skyrim_bleakfalls [arvel_path.txt]  -> src/bfb_kit.inc
import csv, gzip, math, os, re, sys
EXP = sys.argv[1]
PATHF = sys.argv[2] if len(sys.argv) > 2 else None
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'bfb_kit.inc')
refs = [r for r in csv.DictReader(gzip.open(os.path.join(EXP, 'refs.csv.gz'), 'rt', encoding='utf-8')) if r['cell'] in ('BleakFallsBarrow01', 'BleakFallsBarrow02')]
bases = {b['editor_id']: b for b in csv.DictReader(open(os.path.join(EXP, 'bases.csv'), encoding='utf-8'))}
def U(v): return int(v * 143 // 100) if v >= 0 else -int(-v * 143 // 100)
def SY(d): return int(float(d) * 1024 / 360) & 1023
def P(r): return U(float(r['x'])), U(float(r['z'])), U(float(r['y']))
def bounds(e):
    b = bases.get(e, {}).get('bounds', '')
    return [int(v) for v in b.split()] if b else None
def of(cell, pat):
    return [r for r in refs if r['cell'] == cell and re.match(pat, r['base_editor_id'])]
T, S = 'BleakFallsBarrow01', 'BleakFallsBarrow02'
out = ['// generated by docs/maps/gen_bfb_kit.py from the bleakfalls export: the barrow\'s working parts in Skyrim\'s own halls']
def dist(a, b): return math.hypot(a[0] - b[0], a[2] - b[2])

def gate_fix(r, kind, which):
    # its middle and its run across the passage (the bounds' longer side), as turned in the cell
    b = bounds(r['base_editor_id']) or [-108, -7, 0, 108, 7, 250]
    cx, cy = (b[0] + b[3]) / 2.0, (b[1] + b[4]) / 2.0
    a = math.radians(float(r['rot_z'])); ca, sa = math.cos(a), math.sin(a)
    wx = float(r['x']) + cx * ca + cy * sa; wy = float(r['y']) - cx * sa + cy * ca
    along_x = (b[3] - b[0]) >= (b[4] - b[1])
    half = max(b[3] - b[0], b[4] - b[1]) / 2.0
    ang = float(r['rot_z']) + (0 if along_x else 90)          # the direction it runs across
    return [kind, U(wx), U(float(r['z'])), U(wy), SY(ang), which, U(half)]

def cell_tables(cell, key):
    props, ents, fix = [], [], []
    if cell == T:
        pil = sorted(of(T, r'^NorDefaultPuzzlePillar01$'), key=lambda r: float(r['y']))      # south first: item 0
        for i, r in enumerate(pil): x, y, z = P(r); props.append(['PT_PILLAR', x, y, z, SY(r['rot_z']), i])
        for r in of(T, r'^NorLever01$'): x, y, z = P(r); props.append(['PT_LEVER', x, y, z, SY(r['rot_z']), 1])
        g0 = of(T, r'^NorPortcullisLarge01$'); g1 = of(T, r'^NorPortcullis$')
        for r in g0: fix.append(gate_fix(r, 0, 0))
        for r in g1: fix.append(gate_fix(r, 0, 1))
        blades = of(T, r'^TrapBladeSwinging01$')
        chains = of(T, r'^NorPullChain01$')
        for r in blades: x, y, z = P(r); fix.append([3, x, y, z, SY(r['rot_z']), 0, 0])
        for r in chains:
            x, y, z = P(r)
            # the chain past the blades stops them (0); the ones by the small gate raise it (1)
            db = min([dist((x, y, z), P(b)) for b in blades] or [1e9]); dg = min([dist((x, y, z), P(g)) for g in g1] or [1e9])
            props.append(['PT_PULLCHAIN', x, y, z, SY(r['rot_z']), 0 if db < dg else 1])
        for r in of(T, r'^TrapStonePressurePlate02$'): x, y, z = P(r); fix.append([1, x, y, z, 0, 0, 0])
        for r in of(T, r'^TrapWallWood$'): x, y, z = P(r); fix.append([2, x, y, z, SY(r['rot_z']), 0, 0])
        darts = of(T, r'^TrapDartPortSingle0[12]')
        if darts:
            # one volley's place: the darts' middle, at the floor in front of the gate
            x = sum(P(r)[0] for r in darts) // len(darts); z = sum(P(r)[2] for r in darts) // len(darts)
            y = min(P(r)[1] for r in darts) - 60
            fix.append([6, x, y, z, 0, 0, 0])
        for r in of(T, r'^TrapOilPool01$'):
            x, y, z = P(r); b = bounds('TrapOilPool01') or [-80, -80, 0, 80, 80, 2]; fix.append([4, x, y, z, 0, 0, U(max(b[3] - b[0], b[4] - b[1]) / 2.0)])
        for r in of(T, r'^TrapFallingOilLamp01$'): x, y, z = P(r); fix.append([5, x, y, z, 0, 0, 0])
        # the people: the bandits by the fire (they talk; the third waits by the lever), Arvel in the web, the spider
        # above him, the skeevers, the draugr (asleep in their alcoves till you come close), the dead
        # (the third goes to the lever: Skyrim's LeverPushAnimatingNoPlayer, where he pulls it)
        lm = of(T, r'^LeverPushAnimatingNoPlayer$')
        for i, r in enumerate(sorted(of(T, r'^MS13BanditCampfire0[123]$'), key=lambda r: r['base_editor_id'])):
            x, y, z = P(r); yaw = SY(r['rot_z']); kind = 1
            if i == 2 and lm: x, y, z = P(lm[0]); yaw = SY(lm[0]['rot_z']); kind = 4
            ents.append(['E_BANDIT', x, y, z, yaw, len(ents) % 5 + 3, 0, kind])
        for r in of(T, r'^MS13Arvel$'): x, y, z = P(r); ents.append(['E_BANDIT', x, y, z, SY(r['rot_z']), 3, 1, 16])
        amb = of(T, r'^FrostSpiderAmbush01$')
        for r in of(T, r'^MS13FrostbiteSpider$'):
            x, y, z = P(amb[0]) if amb else P(r); fl = P(r)[1]
            ents.append(['E_SPIDER', x, fl, z, SY(r['rot_z']), 0, 0, 8])
    if cell == S:
        for r in of(S, r'^PuzzleDoorBase01$'):
            x, y, z = P(r); props.append(['PT_CLAWDOOR', x, y, z, SY(r['rot_z']), 0])
        for r in of(S, r'^WordWallTrigger$'):
            x, y, z = P(r); props.append(['PT_WORDWALL', x, y, z, SY(r['rot_z']), 0])
        blades = of(S, r'^TrapBladeSwinging01$')
        for r in blades: x, y, z = P(r); fix.append([3, x, y, z, SY(r['rot_z']), 1, 0])
        for r in of(S, r'^NorPullChain01$'): x, y, z = P(r); props.append(['PT_PULLCHAIN', x, y, z, SY(r['rot_z']), 2])
        for r in of(S, r'^TrapOilPool01$'):
            x, y, z = P(r); b = bounds('TrapOilPool01') or [-80, -80, 0, 80, 80, 2]; fix.append([4, x, y, z, 0, 1, U(max(b[3] - b[0], b[4] - b[1]) / 2.0)])
        for r in of(S, r'^TrapFallingOilLamp01$'): x, y, z = P(r); fix.append([5, x, y, z, 0, 1, 0])
        for r in of(S, r'^NorSarcophagusTopAnim01$'): x, y, z = P(r); fix.append([8, x, y, z, SY(r['rot_z']), 0, 0])
    # the chests (the kit leaves them out): what each holds, from the game's barrow tables (1..6; the Overlord's 7)
    k_ = 0
    for r in refs:
        if r['cell'] != cell or r['base_type'] != 'CONT' or not re.match(r'^Treas(Bandit|Draugr|Explorer).*Chest', r['base_editor_id']): continue
        x, y, z = P(r)
        props.append(['PT_CHEST', x, y, z, SY(r['rot_z']), 7 if 'Boss' in r['base_editor_id'] else k_ % 6 + 1]); k_ += 1
    if cell == S:
        for r in of(S, r'^TrapTriggerBox$'): x, y, z = P(r); fix.append([1, x, y, z, 0, 1, 0])     # (the blades' trigger)
    taken = set(); outs = []
    for r in refs:
        if r['cell'] != cell or r['base_type'] != 'NPC_': continue
        e = r['base_editor_id']; fl = int(r['flags'], 16) if r['flags'] else 0
        if fl & 0x800 or r['enable_parent']: continue                    # (not there until something enables it: the troll)
        x, y, z = P(r); yaw = SY(r['rot_z'])
        dead = 2 if fl & 0x200 else 0                                    # (ACHR: starts dead)
        if e == 'EncSkeever': ents.append(['E_SKEEVER', x, y, z, yaw, 0, 0, dead]); continue
        if 'Draugr' in e:
            boss = 'Boss' in e; caster = 'Magic' in e or 'Warlock' in e
            asleep = 'Ambush' in e and not boss
            hide = 0
            if asleep:
                # (v0.4.62) where Skyrim's ambusher sleeps: the nearest free alcove (CreatureAlcove(Bg)Marker: standing
                # in the wall, facing out) or sarcophagus (NorSarcophagusTop: lying in it, out of sight) within 4.5 m -
                # its own place (where Skyrim puts it) is where it steps out to when woken
                sx, sy, sz = float(r['x']), float(r['y']), float(r['z'])
                spots = [(math.dist((sx, sy, sz), (float(q['x']), float(q['y']), float(q['z']))), q) for q in refs
                         if q['cell'] == cell and re.match(r'^(CreatureAlcove(Bg)?Marker|NorSarcophagusTop)$', q['base_editor_id']) and q['ref_id'] not in taken]
                spots = [t for t in spots if t[0] < 320]
                if spots:
                    q = min(spots, key=lambda t: t[0])[1]; taken.add(q['ref_id'])
                    outs.append([len(ents), x, z])
                    x, y, z = P(q); yaw = SY(q['rot_z'])
                    if q['base_editor_id'].startswith('NorSarcophagus'): hide = 8
            ents.append(['E_WIGHT', x, y, z, yaw, len(ents) % 6, 2 if boss else (1 if caster else 0), (64 if boss else (32 if asleep else 0)) | hide | dead])
    # (v0.4.62) the sarcophagi's lids where a draugr sleeps under them: moved aside as it wakes (the game hides the
    # lid's own piece and draws it moving; kind 8 as the Overlord's, f[5] 1: a sleeper's)
    for r in of(cell, r'^NorSarcophagusTop$'):
        if r['ref_id'] in taken:
            x, y, z = P(r); fix.append([8, x, y, z, SY(r['rot_z']), 1, 0])
    return props, ents, fix, outs

for cell, key in ((T, 'BFKTEMPLE'), (S, 'BFKSANCTUM')):
    props, ents, fix, outs = cell_tables(cell, key)
    out.append('static const DunProp K%sProp[] = {' % key)
    for p in props: out.append('    { %s, %d, %d, %d, %d, %d },' % tuple(p))
    out.append('    { -1, 0, 0, 0, 0, 0 } };')
    out.append('static const int K%sEnt[] = {' % key)
    for e in ents: out.append('    %s, %d, %d, %d, %d, %d, %d, %d,' % tuple(e))
    out.append('    -1 };')
    out.append('static const int K%sFix[%d] = {' % (key, max(1, 7 * len(fix))))
    for f in fix: out.append('    %s,' % ', '.join(str(v) for v in f))
    if not fix: out.append('    0')
    out.append('    };')
    out.append('enum { K%sFix_N = %d };' % (key, len(fix)))
    # (v0.4.62) the ambushers asleep in an alcove or a sarcophagus: their number, where they step out to (cm)
    out.append('static const int K%sOut[] = { %s-1 };' % (key, ''.join('%d, %d, %d, ' % tuple(o) for o in outs)))
    print('%s: %d props, %d people and creatures, %d fixtures' % (cell, len(props), len(ents), len(fix)))
# Arvel's run from the web towards the claw's door (host/bfbkpath.cpp walks it over the halls' own floors)
pts = []
if PATHF and os.path.exists(PATHF): pts = [int(v) for v in open(PATHF).read().split()]
arv = of(T, r'^MS13Arvel$'); plate = of(T, r'^TrapStonePressurePlate02$')
if not pts and arv and plate: pts = [P(arv[0])[0], P(arv[0])[2], P(plate[0])[0], P(plate[0])[2]]
out.append('static const int KBFKArvelPath[%d] = { %s };' % (max(2, len(pts)), ', '.join(str(v) for v in pts) or '0, 0'))
out.append('enum { KBFKArvelPath_N = %d };' % (len(pts) // 2))
# the plate's and the web's places (for finding the way)
for nm, rr in (('PLATE', plate), ('WEB', arv)):
    if rr: x, y, z = P(rr[0]); out.append('enum { BFK_%s_X = %d, BFK_%s_Y = %d, BFK_%s_Z = %d };' % (nm, x, nm, y, nm, z))
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote', OUT)
