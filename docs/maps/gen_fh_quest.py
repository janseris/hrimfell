#!/usr/bin/env python3
# (v0.4.69) Siege on the Dragon Cult (dunForelhostQST), its words Skyrim's own: the forelhost export's dialogue.csv
# (speaker "quest:dunForelhostQST"; tools/skyrim_area.py v0.4.68) and quests.csv (the journal's entries). The
# conversations as the game plays them - pages "Speaker|text", the player's topic as "You|..." - by the lines' info ids.
#   python3 docs/maps/gen_fh_quest.py /home/claude/fh_in2/skyrim_forelhost  -> src/fh_quest.inc
import csv, os, sys
EXP = sys.argv[1]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'fh_quest.inc')
rows = [r for r in csv.DictReader(open(os.path.join(EXP, 'dialogue.csv'), encoding='utf-8')) if r['speaker'] == 'quest:dunForelhostQST']
by = {}
for r in rows: by.setdefault(r['info_id'], []).append(r)
def lines(iid, who='Valmir'):
    rs = sorted(by[iid], key=lambda r: int(r['response']))
    return ['%s|%s' % (who, r['text']) for r in rs]
def topic(iid): return 'You|' + by[iid][0]['topic_text']
def first_topic(tp):
    return next(r['info_id'] for r in rows if r['topic'] == tp)
S = 'Stormcloak Soldier'
conv = [
    ('DDF_INTRO', lines('0006223C') + [topic('00090EF1')] + lines('00090EF1')
        + [topic(first_topic('dunForelhostQSTGreetForelhostBranchTopic'))] + lines(first_topic('dunForelhostQSTGreetForelhostBranchTopic'))
        + [topic(first_topic('dunForelhostQSTGreetDragonCultBranchTopic'))] + lines(first_topic('dunForelhostQSTGreetDragonCultBranchTopic'))
        + [topic('00090EE6')] + lines('00090EE6') + lines('0006DE7B') + lines('0006DE7C') + lines('0006DE7D')),
    ('DDF_MID', lines('000C3524') + [topic('00062238')] + lines('00062238') + [topic('0006223B')] + lines('0006223B')),
    ('DDF_JOURNAL', [topic('0006223D')] + lines('0006223D') + lines('00090EE4') + lines('00090EE7') + lines('00090EEA')
        + [topic('00093BC5')] + lines('00093BC5')),
    ('DDF_END', lines('00090EE2') + lines('000729F6', S) + lines('000729EC') + lines('000729F5') + lines('000729EF', S)
        + lines('000729F2', S) + lines('000729F3', S) + lines('000729F4', S) + lines('000729EE')),
    ]
def cs(t): return '"' + t.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['// generated by docs/maps/gen_fh_quest.py from the forelhost export: Siege on the Dragon Cult, Skyrim\'s words']
out.append('enum { %s, DDF_COUNT };' % ', '.join(n for n, _ in conv))
allp = []; ix = []
for n, ps in conv: ix.append((len(allp), len(ps))); allp += ps
out.append('static const char* const KFhLines[%d] = {' % len(allp))
for p in allp: out.append('    %s,' % cs(p))
out.append('    };')
out.append('static const short KFhDlg[DDF_COUNT * 2] = { %s };' % ', '.join('%d, %d' % q for q in ix))
# the journal's entries by stage (quests.csv)
log = {}
for r in csv.DictReader(open(os.path.join(EXP, 'quests.csv'), encoding='utf-8')):
    if r['quest'] == 'dunForelhostQST' and r['kind'] in ('stage', 'objective') and r['text']: log.setdefault((r['kind'], int(r['index'])), r['text'])
for kind in ('stage', 'objective'):
    ks = sorted(i for k, i in log if k == kind)
    out.append('static const short KFh%sN[%d] = { %s };' % ('Log' if kind == 'stage' else 'Obj', len(ks), ', '.join(str(i) for i in ks)))
    out.append('static const char* const KFh%s[%d] = {' % ('Log' if kind == 'stage' else 'Obj', len(ks)))
    for i in ks: out.append('    %s,' % cs(log[(kind, i)]))
    out.append('    };')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote %s: %d pages' % (OUT, len(allp)))
