#!/usr/bin/env python3
# The Sleeping Giant Inn (RiverwoodSleepingGiantInn), from Skyrim's own placements (tools/skyrim_places.py ->
# refs_interiors.csv): writes src/sginn_ext.inc. Everything stays in Skyrim units (x east, y north, z up; game_cells.cpp
# turns them into cm, x 1.43) and Skyrim rotations in degrees, so the tables can be checked against the export.
#   python3 docs/maps/gen_sginn.py path/to/skyrim_places
import csv, os, sys

P = sys.argv[1] if len(sys.argv) > 1 else 'skyrim_places'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'sginn_ext.inc')
rows = [r for r in csv.DictReader(open(os.path.join(P, 'refs_interiors.csv'))) if r['cell'] == 'RiverwoodSleepingGiantInn']

def i(v): return int(round(float(v)))
def sc(r): return int(round(float(r['scale']) * 256))

# statics: Skyrim base -> our model, scale factor on top of the reference's own
STAT = [('CandleHornChandelier01', 'IN_CHANDELIER', 0.43), ('CandleHornFloor01', 'IN_HORNCANDLE', 1), ('CandleHornWall01', 'IN_WALLHORN', 1),
        ('WallMountedElk', 'IN_ELKHEAD', 1), ('PeltHanging02', 'IN_WALLPELT', 0.98), ('PeltHanging03', 'IN_WALLPELT2', 0.98),
        ('PeltHanging01', 'IN_WALLPELT', 0.98), ('PeltFloor', 'IN_RUGLOW', 1.17), ('HangingAnimalsRing', 'IN_HANG', 0.9),
        ('CommonShelf01', 'IN_RWTSHELF', 1), ('CommonTableRound01', 'IN_TABLE', 1.14), ('CommonTableSquare01', 'IN_SQTABLE', 1),
        ('NobleTableShort01', 'IN_SQTABLE', 1.05), ('NobleTableThin01', 'IN_LONGTABLE', 0.9), ('NobleEndTable01', 'IN_ENDTABLE', 1),
        ('CommonTableLow02', 'IN_ENDTABLE', 1), ('CommonTable02', 'IN_LONGTABLE', 1.1),
        ('MeadBarrel01', 'IN_KEG', 0.55), ('Barrel02Static', 'IN_KEG', 1), ('BreweryCaskLargeClosed01', 'IN_KEG', 2.2),
        ('FirewoodPileLarge01', 'IN_FIREWOOD', 1.3), ('FirewoodPileSmall01', 'IN_FIREWOOD', 0.55),
        ('HayBale01', 'IN_SACKS', 0.9), ('PracticeDummy01', 'IN_DUMMY', 1), ('WeaponRackMid', 'IN_WEAPRACK', 1),
        ('CraftingEnchantingWorkbenchTabletop', 'IN_ENCHTOP', 1)]
# containers and furniture: Skyrim base -> prop kind, item (beds: 1 single)
PROP = [('BarrelFood01', 'PT_BARREL', 0), ('BarrelFish01', 'PT_BARREL', 0), ('BarrelIngredientCommon01', 'PT_BARREL', 0),
        ('CommonWardrobe01', 'PT_CUPBOARD', 0), ('Dresser01', 'PT_DRESSER', 0), ('TreasBanditChest', 'PT_CHEST', 0),
        ('DelphineSecretRoomChest', 'PT_CHEST', 0), ('MQ201PlayerContainer', 'PT_CHEST', 0), ('MiscSack', 'PT_SACK', 0),
        ('CommonBed01', 'PT_BED', 1), ('NobleBedSingle01', 'PT_BED', 1), ('WoodenChair01', 'PT_CHAIR', 0),
        ('CommonChair01', 'PT_CHAIR', 0), ('NobleChair01', 'PT_CHAIR', 0), ('CraftingAlchemyWorkbench', 'PT_ALCHEMY', 0),
        ('HangingGarlicBraid', 'PT_GARLIC', 0)]
ITEM = [('BasicTankard01', 'IT_TANKARD'), ('FoodBread01', 'IT_BREAD'), ('BasicWoodenPlate01', 'IT_PLATE'),
        ('FoodSalmonCooked', 'IT_SALMON_STEAK'), ('FoodApple', 'IT_APPLE'), ('RestoreStamina', 'IT_POT_MSTAM'),
        ('FoodCheese', 'IT_CHEESE'), ('BasicWoodenBowl', 'IT_WOOD_BOWL')]

stat, prop, item, flame, light, door, people, tables = [], [], [], [], [], [], [], []
for r in rows:
    e, k = r['base_editor_id'], r['base_type']
    x, y, z, rz = i(r['x']), i(r['y']), i(r['z']), i(r['rot_z']) % 360
    if z < -300: continue
    if e == 'FarmTable01':
        tables.append((x, y, z, rz)); continue
    if e.startswith('FireplaceWood01Burning'):
        flame.append((x, y, z, sc(r))); continue
    if k == 'LIGH':
        light.append((x, y, z, 1 if 'Fire' in e else 0)); continue
    if e.startswith('CandleHornTable01'):
        stat.append(('IN_CANDLE', x, y, z, rz, 256)); continue
    if k == 'DOOR' and e.startswith('FarmhouseAnimDoor'):
        door.append((x, y, z, rz)); continue
    if k == 'NPC_':
        people.append((e, x, y, z, rz)); continue
    hit = [s for s in STAT if e.startswith(s[0])]
    if hit and k in ('STAT', 'ACTI', 'FURN'):
        if e == 'WeaponRackMidACTIVATOR': continue
        s = hit[0]; stat.append((s[1], x, y, z, rz, int(round(sc(r) * s[2])))); continue
    hit = [s for s in PROP if e.startswith(s[0])]
    if hit and k in ('CONT', 'FURN', 'FLOR'):
        if e.startswith('Merchant'): continue
        s = hit[0]; prop.append((s[1], x, y, z, rz, s[2])); continue
    hit = [s for s in ITEM if e.startswith(s[0])]
    if hit and k in ('MISC', 'ALCH'):
        item.append((hit[0][1], x, y, z)); continue

def emit(f, name, rowsx, n):
    f.write('enum { %s_N = %d };\nstatic const int %s[%d] = {\n' % (name, len(rowsx), name, max(1, len(rowsx) * n)))
    for t in rowsx: f.write('    ' + ', '.join(str(v) for v in t) + ',\n')
    if not rowsx: f.write('    0\n')
    f.write('    };\n')
with open(OUT, 'w') as f:
    f.write('// generated by docs/maps/gen_sginn.py from Skyrim.esm (RiverwoodSleepingGiantInn) - do not edit by hand\n')
    f.write('// Skyrim units (x east, y north, z up; x 1.43 = cm), rotations in degrees clockwise from north\n')
    f.write('// statics: model, x, y, z, rotation, scale (256 = 1)\n'); emit(f, 'KSgStat', stat, 6)
    f.write('// props: kind, x, y, z, rotation, item (beds: 1 single)\n'); emit(f, 'KSgProp', prop, 6)
    f.write('// things on the tables and shelves: item, x, y, z\n'); emit(f, 'KSgItem', item, 4)
    f.write('// FarmTable01 (a long table with its bench on the room side, local +y): x, y, z, rotation\n'); emit(f, 'KSgTable', tables, 4)
    f.write('// the fires in the pit: x, y, z, scale\n'); emit(f, 'KSgFlame', flame, 4)
    f.write('// lights: x, y, z, fire\n'); emit(f, 'KSgLight', light, 4)
    f.write('// the rooms\' doors (FarmhouseAnimDoor): x, y, z, rotation\n'); emit(f, 'KSgDoor', door, 4)
    f.write('// the people: x, y, z, rotation (%s)\n' % ', '.join(p[0] for p in people)); emit(f, 'KSgPeople', [p[1:] for p in people], 4)
print('statics', len(stat), 'props', len(prop), 'items', len(item), 'tables', len(tables), 'flames', len(flame),
      'lights', len(light), 'doors', len(door), 'people', [p[0] for p in people])
