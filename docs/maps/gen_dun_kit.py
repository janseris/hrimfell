#!/usr/bin/env python3
# (v0.4.68) A Nordic ruin's working parts in Skyrim's own halls, from where Skyrim places each thing - any ruin's (the
# same tables game_dungeon.cpp has for Bleak Falls Barrow, gen_bfb_kit.py; that one's puzzles and its story are its
# own): the chests, the levers and the portcullises they raise, the claw door and its claw, the sarcophagi's lids, the
# draugr (asleep in their alcoves and sarcophagi till you come close), their bosses, the ghosts, the skeevers and
# spiders, the dead. In the interiors' frame (cm, y up from the floor level): x = Skyrim x * 1.43, y = Skyrim z * 1.43,
# z = Skyrim y * 1.43 (game_kit.cpp U()).
#   python3 docs/maps/gen_dun_kit.py <export folder> <key> <out.inc> <Cell>=<KEY> ...
#   python3 docs/maps/gen_dun_kit.py /home/claude/fh_in/skyrim_forelhost FH src/fh_kit.inc Forelhost01=FH1 Forelhost02=FH2 Forelhost03=FH3
# Fixture "which" numbers (f[5]) and lever items are the ruin's own (0..): the game adds its ruin's base (game_dungeon.cpp).
import csv, gzip, math, os, re, sys
EXP, KEY, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
CELLS = [a.split('=') for a in sys.argv[4:]]
want = set(c for c, _ in CELLS)
allrefs = list(csv.DictReader(gzip.open(os.path.join(EXP, 'refs.csv.gz'), 'rt', encoding='utf-8')))
refs = [r for r in allrefs if r['cell'] in want]
bases = {b['editor_id']: b for b in csv.DictReader(open(os.path.join(EXP, 'bases.csv'), encoding='utf-8'))}
def U(v): return int(v * 143 // 100) if v >= 0 else -int(-v * 143 // 100)
def SY(d): return int(float(d) * 1024 / 360) & 1023
def P(r): return U(float(r['x'])), U(float(r['z'])), U(float(r['y']))
def bounds(e):
    b = bases.get(e, {}).get('bounds', '')
    try: return [int(float(v)) for v in b.split()] if b else None
    except ValueError: return None
def of(cell, pat): return [r for r in refs if r['cell'] == cell and re.match(pat, r['base_editor_id'])]
def flags(r): return int(r['flags'] or '0', 16)
def dist(a, b): return math.hypot(a[0] - b[0], a[2] - b[2])
out = ['// generated by docs/maps/gen_dun_kit.py from the %s export: a Nordic ruin\'s working parts in Skyrim\'s own halls' % os.path.basename(EXP)]

def gate_fix(r, which):
    # its middle and its run across the passage (the bounds' longer side), as turned in the cell
    b = bounds(r['base_editor_id']) or [-108, -7, 0, 108, 7, 250]
    cx, cy = (b[0] + b[3]) / 2.0, (b[1] + b[4]) / 2.0
    a = math.radians(float(r['rot_z'])); ca, sa = math.cos(a), math.sin(a)
    wx = float(r['x']) + cx * ca + cy * sa; wy = float(r['y']) - cx * sa + cy * ca
    along_x = (b[3] - b[0]) >= (b[4] - b[1])
    half = max(b[3] - b[0], b[4] - b[1]) / 2.0
    ang = float(r['rot_z']) + (0 if along_x else 90)
    return [0, U(wx), U(float(r['z'])), U(wy), SY(ang), which, U(half)]

ngate = 0; nchest = 0; claw = None
def cell_tables(cell):
    global ngate, nchest, claw
    props, ents, fix = [], [], []
    # the portcullises (each its number), and the levers: each raises the nearest one in its cell
    gates = []
    for r in of(cell, r'^NorPortcullis'):
        if flags(r) & 0x800: continue
        fix.append(gate_fix(r, ngate)); gates.append((ngate, P(r))); ngate += 1
    for r in of(cell, r'^NorLever01$'):
        x, y, z = P(r)
        g = min(gates, key=lambda q: dist((x, y, z), q[1]))[0] if gates else 255
        props.append(['PT_LEVER', x, y, z, SY(r['rot_z']), 100 + g])          # (100 + the gate's number: a ruin's lever)
    # the claw door (its rings) and its claw where Skyrim leaves it
    for r in of(cell, r'^PuzzleDoorBase01$'):
        x, y, z = P(r); props.append(['PT_CLAWDOOR', x, y, z, SY(r['rot_z']), 1])
    for r in of(cell, r'^dunForelhostGlassClaw$'):
        x, y, z = P(r); claw = (cell, x, y, z, SY(r['rot_z']))
    # the chests: what each holds (the game's barrow tables 1..6; a boss's 7)
    for r in refs:
        if r['cell'] != cell or r['base_type'] != 'CONT' or not re.match(r'^Treas(Bandit|Draugr|Explorer).*Chest', r['base_editor_id']): continue
        if 'EMPTY' in r['base_editor_id']: continue
        x, y, z = P(r)
        props.append(['PT_CHEST', x, y, z, SY(r['rot_z']), 7 if 'Boss' in r['base_editor_id'] else nchest % 6 + 1]); nchest += 1
    # the people and creatures
    taken = set(); outs = []
    for r in refs:
        if r['cell'] != cell or r['base_type'] != 'NPC_': continue
        e = r['base_editor_id']; fl = flags(r)
        if fl & 0x800: continue                                             # (initially disabled)
        if r['enable_parent'] and 'Rahgot' not in e: continue               # (not there until something enables it)
        x, y, z = P(r); yaw = SY(r['rot_z'])
        dead = 2 if fl & 0x200 else 0                                       # (starts dead)
        if e.startswith('EncSkeever'): ents.append(['E_SKEEVER', x, y, z, yaw, 0, 0, dead]); continue
        if 'FrostbiteSpider' in e: ents.append(['E_SPIDER', x, y, z, yaw, 0, 0, dead]); continue
        if 'Corpse' in e and 'Draugr' not in e: continue                    # (the dead of other kinds: not people of ours yet)
        if 'Rahgot' in e:
            ents.append(['E_WIGHT', x, y, z, yaw, 0, 4, 32 | dead]); continue          # the dragon priest (wakes as you come)
        if 'Ghost' in e:
            ents.append(['E_WIGHT', x, y, z, yaw, len(ents) % 6, 3, dead]); continue    # Forelhost's ghosts: the cult's dead
        if 'Draugr' in e:
            boss = 'Boss' in e; caster = 'Magic' in e or 'Warlock' in e
            asleep = 'Ambush' in e
            hide = 0
            if asleep:
                # where Skyrim's ambusher sleeps: the nearest free alcove (CreatureAlcove(Bg)Marker: standing in the wall,
                # facing out) or sarcophagus (NorSarcophagusTop: lying in it; NorSarcophagusVertTop: standing in it,
                # out of sight) within 3.2 m - its own place (where Skyrim puts it) is where it steps out to
                sx, sy, sz = float(r['x']), float(r['y']), float(r['z'])
                spots = [(math.dist((sx, sy, sz), (float(q['x']), float(q['y']), float(q['z']))), q) for q in refs
                         if q['cell'] == cell and re.match(r'^(CreatureAlcove(Bg)?Marker|NorSarcophagusTop|NorSarcophagusVertTop\w*)$', q['base_editor_id'])
                         and q['ref_id'] not in taken]
                spots = [t for t in spots if t[0] < 320]
                if spots:
                    q = min(spots, key=lambda t: t[0])[1]; taken.add(q['ref_id'])
                    outs.append([len(ents), x, z])
                    x, y, z = P(q); yaw = SY(q['rot_z'])
                    if q['base_editor_id'].startswith('NorSarcophagus'): hide = 8
            ents.append(['E_WIGHT', x, y, z, yaw, len(ents) % 6, 5 if boss else (1 if caster else 0), (32 if asleep else 0) | hide | dead])
    # the sarcophagi's lids where a draugr sleeps under them: moved aside as it wakes
    for r in of(cell, r'^NorSarcophagusTop$'):
        if r['ref_id'] in taken:
            x, y, z = P(r); fix.append([8, x, y, z, SY(r['rot_z']), 1, 0])
    return props, ents, fix, outs

for cell, key in CELLS:
    props, ents, fix, outs = cell_tables(cell)
    out.append('static const DunProp K%sProp[] = {' % key)
    for p in props: out.append('    { %s, %d, %d, %d, %d, %d },' % tuple(p))
    out.append('    { -1, 0, 0, 0, 0, 0 } };')
    out.append('static const int K%sEnt[] = {' % key)
    for e in ents: out.append('    %s, %d, %d, %d, %d, %d, %d, %d,' % tuple(e))
    out.append('    -1 };')
    out.append('static const int K%sFix[%d] = {' % (key, max(1, 7 * len(fix))))
    for f in fix: out.append('    %s,' % ', '.join(str(v) for v in f))
    if not fix: out.append('    0')
    out.append('    };')
    out.append('enum { K%sFix_N = %d };' % (key, len(fix)))
    out.append('static const int K%sOut[] = { %s-1 };' % (key, ''.join('%d, %d, %d, ' % tuple(o) for o in outs)))
    print('%s: %d props, %d people and creatures, %d fixtures' % (cell, len(props), len(ents), len(fix)))
out.append('enum { K%sGates = %d };' % (KEY, ngate))
# the claw where Skyrim leaves it (its cell's number among the ruin's, cm and its turn)
if claw:
    ci = [c for c, _ in CELLS].index(claw[0])
    out.append('enum { K%sClawCell = %d, K%sClawX = %d, K%sClawY = %d, K%sClawZ = %d, K%sClawYaw = %d };' % (KEY, ci, KEY, claw[1], KEY, claw[2], KEY, claw[3], KEY, claw[4]))
# the word wall outside (Tamriel, Skyrim units) and the words on it
ww = [r for r in allrefs if r['world'] == 'Tamriel' and r['base_editor_id'].startswith('NorWordWallWord')]
if ww:
    r = ww[0]
    out.append('enum { K%sWallX = %d, K%sWallY = %d, K%sWallZ = %d };     // %s' % (KEY, int(float(r['x'])), KEY, int(float(r['y'])), KEY, int(float(r['z'])),
                                                                         ' '.join(q['base_editor_id'][15:] for q in ww)))
    walls = [q for q in allrefs if q['world'] == 'Tamriel' and re.match(r'^NorWordWall0', q['base_editor_id'])]
    if walls:
        w_ = min(walls, key=lambda q: math.hypot(float(q['x']) - float(r['x']), float(q['y']) - float(r['y'])))
        out.append('enum { K%sWallRot = %d };' % (KEY, int(float(w_['rot_z']))))
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote', OUT)
